CREATE TABLE employee_leave_guard (
    employee_id BIGINT PRIMARY KEY,
    CONSTRAINT ck_employee_leave_guard_employee_id CHECK (employee_id > 0)
);

CREATE TABLE leave_balances (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL,
    leave_type VARCHAR(20) NOT NULL,
    total_days INTEGER NOT NULL,
    used_days INTEGER NOT NULL DEFAULT 0,
    available_days INTEGER NOT NULL,
    CONSTRAINT uk_leave_balances_employee_type UNIQUE (employee_id, leave_type),
    CONSTRAINT ck_leave_balances_employee_id CHECK (employee_id > 0),
    CONSTRAINT ck_leave_balances_leave_type CHECK (leave_type IN ('CASUAL', 'SICK', 'EARNED')),
    CONSTRAINT ck_leave_balances_days_nonnegative
        CHECK (total_days >= 0 AND used_days >= 0 AND available_days >= 0),
    CONSTRAINT ck_leave_balances_days_consistent
        CHECK (total_days = used_days + available_days)
);

CREATE INDEX ix_leave_balances_employee_id ON leave_balances (employee_id);

CREATE TABLE leave_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL,
    leave_type VARCHAR(20) NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    number_of_days INTEGER NOT NULL,
    reason VARCHAR(1000) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    approved_by BIGINT,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_leave_requests_leave_type CHECK (leave_type IN ('CASUAL', 'SICK', 'EARNED')),
    CONSTRAINT ck_leave_requests_status
        CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'CANCELLED')),
    CONSTRAINT ck_leave_requests_employee_id CHECK (employee_id > 0),
    CONSTRAINT ck_leave_requests_approved_by CHECK (approved_by IS NULL OR approved_by > 0),
    CONSTRAINT ck_leave_requests_dates CHECK (end_date >= start_date),
    CONSTRAINT ck_leave_requests_number_of_days CHECK (
        number_of_days > 0 AND number_of_days = end_date - start_date + 1
    )
);

CREATE INDEX ix_leave_requests_employee_id ON leave_requests (employee_id);
CREATE INDEX ix_leave_requests_status ON leave_requests (status);
CREATE INDEX ix_leave_requests_overlap
    ON leave_requests (employee_id, status, start_date, end_date);
